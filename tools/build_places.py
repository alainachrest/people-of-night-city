"""Builds the mod's places (homes and workplaces) from the doors in the game's
world data.

data/doors.json comes from the game's exterior streaming sectors: every door
entity on the outside of a building, as
  [x, y, z, qi, qj, qk, qr, template, kind, nodeClass]
kind: "decorative" (a door that never opens: no interior), "door" (a working
door), "shutter" (a shop shutter), "freight".

  python build_places.py CYBERSCRIPT_DISTRICTS_JSON OUT_LUA
"""
import json
import math
import sys

DISTRICTS = {
    "district_watson": "watson", "district_westbrook": "westbrook", "district_downtown": "citycenter",
    "district_heywood": "heywood", "district_santodomingo": "santodomingo", "district_pacifica": "pacifica",
    "district_badland": "badlands",
}
COMMERCIAL = ("double_door", "shutter", "mall_shutter", "freight", "glass", "sliding")


def inside(poly, x, y):
    hit, j = False, len(poly) - 1
    for i in range(len(poly)):
        a, b = poly[i], poly[j]
        if (a["y"] > y) != (b["y"] > y) and x < (b["x"] - a["x"]) * (y - a["y"]) / (b["y"] - a["y"]) + a["x"]:
            hit = not hit
        j = i
    return hit


def main(districts_path, out_path):
    doors = json.load(open("data/doors.json"))
    districts = json.load(open(districts_path))
    seen = set()
    rows = []
    skipped = {"duplicate": 0, "underground": 0, "outside": 0}
    for x, y, z, qi, qj, qk, qr, template, kind, _cls in doors:
        key = (round(x), round(y), round(z))
        if key in seen:
            skipped["duplicate"] += 1
            continue
        seen.add(key)
        if z < -40:            # sealed-off areas below the city
            skipped["underground"] += 1
            continue
        district = None
        for d in districts:
            if inside(d["Polygon"], x, y):
                district = DISTRICTS.get(d["Tag"])
                break
        if district is None:
            skipped["outside"] += 1
            continue
        yaw = math.degrees(math.atan2(2 * (qr * qk + qi * qj), 1 - 2 * (qj * qj + qk * qk)))
        use = "work" if any(template.startswith(c) or c in template for c in COMMERCIAL) else "home"
        rows.append((x, y, z, round(yaw, 1), use, kind, district))
    rows.sort(key=lambda r: (r[6], r[0], r[1]))
    with open(out_path, "w") as fh:
        fh.write("-- Generated by tools/build_places.py from the doors in the game's world data.\n")
        fh.write("-- { x, y, z, yaw, use (home/work), door (decorative/door/shutter/freight), district }\n")
        fh.write("return {\n")
        for r in rows:
            fh.write('{%.2f,%.2f,%.2f,%.1f,"%s","%s","%s"},\n' % r)
        fh.write("}\n")
    from collections import Counter
    print(len(rows), "places", skipped)
    print(Counter(r[4] for r in rows), Counter(r[6] for r in rows), Counter(r[5] for r in rows))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
